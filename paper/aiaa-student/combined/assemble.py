"""Assemble the combined paper (impossibility + landing algorithm) from one hand-written front half (front.tex)
and the sections of ../algorithm/main.tex that carry the program, its proof and the closed-loop table.

Usage (from this directory):  python3 assemble.py   ->  main.tex
The algorithm paper stays the single source for the program and the soundness proof, so the two cannot drift apart.
"""
import pathlib
import re

HERE = pathlib.Path(__file__).resolve().parent
alg = (HERE / '..' / 'algorithm' / 'main.tex').read_text()
front = (HERE / 'front.tex').read_text()
back = (HERE / 'back.tex').read_text()


def between(s, a, b, keep_a=True):
    i = s.index(a)
    j = s.index(b, i)
    return s[i if keep_a else i + len(a):j]


# vehicle model and center of percussion, without the schematic figure
model = between(alg, r'\section{Vehicle Model and the Center of Percussion}', r'\section{Why an Exact Convex Formulation Does Not Exist}')
fig = between(model, r'\begin{figure}[t]', r'\end{figure}') + r'\end{figure}' + '\n\n'
model = model.replace(fig, '').replace(r' (Fig.~\ref{fig:schematic})', '')
model = model.replace(r'\section{Vehicle Model and the Center of Percussion}\label{sec:model}',
                      r'\section{The Gimbaled Rigid Body and Its Center of Percussion}\label{sec:model}')
model = model.replace(r'Table~\ref{tab:vehicle} lists the values used in this paper.',
                      r'Table~\ref{tab:vehicle} lists the values used in this paper. In contrast to the model of Sec.~\ref{sec:problem}, the body is now turned by the thrust itself.')

# program, soundness theorem and proof, incompleteness
prog = between(alg, r'\section{A Sound Convex Program}', r'\section{Guidance Algorithm}')
prog = prog.replace(r'the projection argument of' + '\n' + r'Sec.~\ref{sec:imposs} gives convexity', r'the projection argument of' + '\n' + r'Theorem~\ref{thm:A} gives convexity')
prog = prog.replace(r'which is the maneuver the obstruction of' + '\n' + r'Sec.~\ref{sec:imposs} is built from', r'which is the maneuver the obstruction of' + '\n' + r'Sec.~\ref{sec:dive} is built from')
assert 'sec:imposs' not in prog

closed = between(alg, r'\begin{table}[t]\centering' + '\n' + r'\caption{Closed-loop results', r'\end{table}') + r'\end{table}' + '\n'

tdfig = between(alg, r'\begin{figure}[t]\centering' + '\n' + r'\includegraphics[width=\linewidth]{figures/touchdown.pdf}', r'\end{figure}') + r'\end{figure}' + '\n'

body = front.replace('%%MODEL%%', model).replace('%%PROGRAM%%', prog) + back.replace('%%CLOSEDTABLE%%', closed).replace('%%TDFIG%%', tdfig)

# bibliography: entries of the algorithm paper, in order of first citation here
bib = between(alg, r'\begin{thebibliography}{99}', r'\end{thebibliography}', keep_a=False)
items = {m.group(1): m.group(0).strip() for m in re.finditer(r'\\bibitem\{([^}]+)\}.*?(?=\\bibitem|\Z)', bib, flags=re.S)}
order = []
for m in re.finditer(r'\\cite\{([^}]+)\}', body):
    for k in m.group(1).split(','):
        k = k.strip()
        if k not in order:
            order.append(k)
missing = [k for k in order if k not in items]
assert not missing, missing
body += '\n\\begin{thebibliography}{99}\n' + '\n'.join(items[k] for k in order) + '\n\\end{thebibliography}\n\\end{document}\n'
(HERE / 'main.tex').write_text('% GENERATED by assemble.py from front.tex, back.tex and ../algorithm/main.tex. Edit those, not this file.\n' + body)
print('wrote main.tex,', len(order), 'references')
